#!/usr/bin/env node

/**
 * Vendor Telegram's MTProto schema from TDLib into src/services/telegram-schema-tl.ts.
 *
 * GramJS 2.26 ships layer 198 and has not published a newer one. It builds its
 * API classes from a schema string at load time, so a newer schema can be
 * swapped in without forking the library (see src/services/telegram-schema.ts).
 *
 * Usage: node scripts/update-telegram-schema.mjs [tdlib-ref]   (default: master)
 */

import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const ref = process.argv[2] || 'master';
const base = `https://raw.githubusercontent.com/tdlib/td/${ref}`;
const out = join(dirname(fileURLToPath(import.meta.url)), '../src/services/telegram-schema-tl.ts');

async function fetchText(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

const schema = await fetchText(`${base}/td/generate/scheme/telegram_api.tl`);
const version = await fetchText(`${base}/td/telegram/Version.h`);

const layer = Number(/MTPROTO_LAYER\s*=\s*(\d+)/.exec(version)?.[1]);
if (!layer) throw new Error('MTPROTO_LAYER not found in Version.h');

// GramJS's parser rejects TDLib's builtin-type declarations (`int ? = Int;`);
// it knows those types natively.
const cleaned = schema
  .split('\n')
  .filter((line) => !/^[A-Za-z0-9]+ \? = /.test(line))
  .join('\n');

if (/[`\\]|\$\{/.test(cleaned)) throw new Error('Schema contains characters unsafe for a template literal');

writeFileSync(out, `// Generated by scripts/update-telegram-schema.mjs from tdlib/td@${ref} - do not edit.
// Generated from TDLib's Telegram scheme, under the Boost Software License 1.0; its full
// statement is in THIRD-PARTY-NOTICES.md, which ships with this package.

export const SCHEMA_LAYER = ${layer};

export const SCHEMA_TL = \`${cleaned}\`;
`);

console.log(`✓ Wrote layer ${layer} schema (${cleaned.split('\n').length} lines) to ${out}`);
